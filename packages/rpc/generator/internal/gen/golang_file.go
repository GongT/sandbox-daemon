package gen

import (
	"fmt"
	"log"
	"os"
	"path"
	"strings"

	"github.com/pkg/errors"
)

const MAGIC = "14817ed6-2e76-4c92-bba3-06cf6df780f2"

type golangFile struct {
	header      *strings.Builder
	packageName string
	imports     *strings.Builder

	body *strings.Builder

	path string
}

func newOutputFile(fPath string) *golangFile {
	package_name := detectPackageName(fPath)

	return &golangFile{
		packageName: package_name,
		header:      &strings.Builder{},
		imports:     &strings.Builder{},
		body:        &strings.Builder{},
		path:        fPath,
	}
}

func (f *golangFile) SafeToWrite() error {
	if _, err := os.Stat(f.path); err != nil {
		return nil // 文件不存在，可以写入
	}
	if data, err := os.ReadFile(f.path); err != nil {
		return errors.WithMessage(err, "读取文件失败")
	} else {
		if strings.Contains(string(data), MAGIC) {
			return nil
		} else {
			return errors.New("目标文件中不存在MAGIC标记，可能是手动修改过的文件，拒绝覆盖")
		}
	}
}

func (f *golangFile) Save() error {
	if err := f.SafeToWrite(); err != nil {
		return err
	}

	content := strings.Builder{}
	content.WriteString("// Code generated by sandbox-daemon rpc generator. DO NOT EDIT.\n")
	content.WriteString("// MAGIC: " + MAGIC + "\n")
	content.WriteString(f.header.String())
	content.WriteString("package ")
	content.WriteString(f.packageName)
	content.WriteString("\n\n")

	if f.imports.Len() > 0 {
		content.WriteString("import (\n")
		content.WriteString(f.imports.String())
		content.WriteString(")\n\n")
	}

	content.WriteString(f.body.String())

	err := os.WriteFile(f.path, []byte(content.String()), 0644)
	return errors.WithMessage(err, "写入文件失败")
}

func detectPackageName(fPath string) string {
	dir, base := path.Split(fPath)

	var otherFile string

	dirs, err := os.ReadDir(dir)
	if err != nil {
		dirs = []os.DirEntry{}
	}
	for f := range dirs {
		if dirs[f].IsDir() {
			continue
		}
		if dirs[f].Name() == base {
			continue
		}
		if strings.HasSuffix(dirs[f].Name(), ".go") {
			otherFile = path.Join(dir, dirs[f].Name())
			break
		}
	}

	var pkgName string
	if otherFile != "" {
		name, err := mustParsePackageName(otherFile)
		if err != nil {
			log.Println(err)
		}
		pkgName = name
	}

	// 如果: 则使用目录名作为包名
	// - 没有其他 Go 文件
	// - 其他 Go 文件解析失败
	if pkgName == "" {
		pkgName = path.Base(dir)
	}

	return pkgName
}

func mustParsePackageName(fPath string) (string, error) {
	ast, err := readAst(fPath)
	if err != nil {
		return "", err
	}

	return ast.Name.Name, nil
}

func (f *golangFile) WriteBody(s ...any) {
	for _, str := range s {
		switch v := str.(type) {
		case string:
			f.body.WriteString(v)
		default:
			fmt.Fprintf(f.body, "%v", v)
		}
	}
}
